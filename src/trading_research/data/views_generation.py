"""Internal Slice 1F snapshot and Tier-1 manifest generation.

This module orchestrates the existing gate-issued grant and sole market-row
decoder.  It never opens a partition itself: one complete
``MarketFrameLoader.load(grant, columns=())`` supplies the observed native
keys, and every generated artefact after that is metadata.

The module is intentionally private to the data package.  Stage B will import
it directly; :mod:`trading_research.data` does not re-export anything here.
"""


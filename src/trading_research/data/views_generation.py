class _ViewGenerationError(RuntimeError):
    """A requested five-view bundle cannot be produced honestly."""


class _ResumeRefusedError(_ViewGenerationError):
    """An existing SNAPSHOT or child contradicts the requested bundle."""


class _GenerationMode(_StrEnum):
    FRESH = "fresh"
    RESUME = "resume"


@_dataclass(frozen=True, slots=True)
class _ViewIds:
    """Explicit generated identities, independent of asset naming conventions."""

    snapshot: str
    train: str
    validation: str
    oos: str
    lockbox: str

    def __post_init__(self) -> None:
        values = tuple(view_id for _, view_id in self.items())
        if len(set(values)) != len(values):
            raise _ViewGenerationError("generated view ids must be distinct")
        for view_id in values:
            try:
                _DatasetIdentity(dataset_id=view_id, manifest_sha256="0" * 64)
            except (TypeError, ValueError) as exc:
                raise _ViewGenerationError(
                    f"generated view id {view_id!r} is not a safe dataset identity"
                ) from exc

    def for_role(self, role: _ViewRole) -> str:
        """Return the explicit id for one generated role."""
        by_role = dict(self.items())
        try:
            return by_role[role]
        except KeyError as exc:
            raise _ViewGenerationError(
                f"role {role.value!r} is not generated by Slice 1F"
            ) from exc

    def items(self) -> tuple[tuple[_ViewRole, str], ...]:
        """Return all five identities in publication order."""
        return (
            (_ViewRole.SNAPSHOT, self.snapshot),
            (_ViewRole.TRAIN, self.train),
            (_ViewRole.VALIDATION, self.validation),
            (_ViewRole.OOS, self.oos),
            (_ViewRole.LOCKBOX, self.lockbox),
        )


@_dataclass(frozen=True, slots=True)
class _GeneratorProvenance:
    """Exact generator identity embedded in every bundle member."""

    name: str
    version: str
    platform_git_commit: str

    def __post_init__(self) -> None:
        if not isinstance(self.name, str) or not self.name:
            raise _ViewGenerationError("generator name must be nonempty")
        if not isinstance(self.version, str) or not self.version:
            raise _ViewGenerationError("generator version must be nonempty")
        if (
            not isinstance(self.platform_git_commit, str)
            or _GIT_COMMIT.fullmatch(self.platform_git_commit) is None
        ):
            raise _ViewGenerationError(
                "generator platform_git_commit must be a 40- or 64-character hex digest"
            )
        object.__setattr__(
            self, "platform_git_commit", self.platform_git_commit.lower()
        )

    def as_wire(self) -> dict[str, str]:
        """Return the strict v1.1 generator fragment."""
        return {
            "name": self.name,
            "version": self.version,
            "platform_git_commit": self.platform_git_commit,
        }


@_dataclass(frozen=True, slots=True)
class _BundleSpec:
    """Explicit location-independent identity and provenance inputs."""

    source_ref: _DatasetRef
    view_ids: _ViewIds
    views_root: _Path
    generated_at_utc: str
    generator: _GeneratorProvenance
    policy_cap_encoded: str

    def __post_init__(self) -> None:
        if not isinstance(self.source_ref, _DatasetRef):
            raise _ViewGenerationError("source_ref must be an exact DatasetRef")
        if self.source_ref.role is not _ViewRole.CURATED:
            raise _ViewGenerationError("Slice 1F source_ref must name CURATED")
        if not isinstance(self.views_root, _Path):
            raise _ViewGenerationError("views_root must be pathlib.Path")
        if not self.views_root.is_absolute():
            raise _ViewGenerationError(
                "views_root must be an explicit absolute path, independent of cwd"
            )
        if not isinstance(self.generated_at_utc, str) or not self.generated_at_utc:
            raise _ViewGenerationError("generated_at_utc must be supplied explicitly")
        if not isinstance(self.policy_cap_encoded, str) or not self.policy_cap_encoded:
            raise _ViewGenerationError("policy_cap_encoded must be supplied explicitly")



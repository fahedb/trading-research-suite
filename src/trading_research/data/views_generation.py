def _binding_event_id(
    *,
    source: _DatasetIdentity,
    partition_source: _DatasetIdentity,
    policy: _SplitPolicy,
    snapshot_view_id: str,
    generated_at_utc: str,
    generator: _GeneratorProvenance,
    policy_cap_encoded: str,
) -> str:
    """Return the stable id for one exact binding procedure and its inputs."""
    identity = policy.identity
    seed = _json.dumps(
        {
            "source": [source.dataset_id, source.manifest_sha256],
            "partition_source": [
                partition_source.dataset_id,
                partition_source.manifest_sha256,
            ],
            "snapshot_view_id": snapshot_view_id,
            "policy": [identity.adr, identity.policy_version, identity.policy_sha256],
            "policy_cap_encoded": policy_cap_encoded,
            "generated_at_utc": generated_at_utc,
            "generator": generator.as_wire(),
            "binding_method": _BINDING_METHOD,
            "binding_procedure": _BINDING_PROCEDURE,
            "binding_procedure_version": _BINDING_PROCEDURE_VERSION,
        },
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    )
    return str(_uuid5(_UUID_NAMESPACE, seed))


def _read_and_validate_anchor(
    *,
    path: _Path,
    spec: _BundleSpec,
    source: _RegisteredManifest,
    partition_source: _DatasetIdentity,
    policy: _SplitPolicy,
    columns: tuple[dict[str, str], ...],
) -> _ResumeAnchor:
    """Read wire provenance and also pass the anchor through the ordinary reader."""
    if path.parent.is_symlink() or path.parent.resolve() != path.parent:
        raise _ResumeRefusedError(
            "existing SNAPSHOT view directory must not traverse a symlink"
        )
    if path.is_symlink() or not path.is_file():
        raise _ResumeRefusedError("existing SNAPSHOT anchor must be a regular file")
    try:
        raw_bytes = path.read_bytes()
        document = _json.loads(raw_bytes)
    except (OSError, UnicodeError, _json.JSONDecodeError) as exc:
        raise _ResumeRefusedError(f"cannot read existing SNAPSHOT anchor: {exc}") from exc
    if not isinstance(document, dict):
        raise _ResumeRefusedError("existing SNAPSHOT wire document is not an object")
    try:
        normalized = _read_manifest(path)
    except Exception as exc:
        raise _ResumeRefusedError(f"existing SNAPSHOT is not valid v1.1: {exc}") from exc

    expected_policy = {
        "adr": policy.identity.adr,
        "policy_version": policy.identity.policy_version,
        "policy_sha256": policy.identity.policy_sha256,
    }
    expected_parent = {
        "dataset_id": source.identity.dataset_id,
        "manifest_sha256": source.identity.manifest_sha256,
    }
    expected_source = {
        "dataset_id": partition_source.dataset_id,
        "manifest_sha256": partition_source.manifest_sha256,
    }
    checks = (
        (document.get("view_id") == spec.view_ids.snapshot, "SNAPSHOT view id"),
        (document.get("role") == _ViewRole.SNAPSHOT.value, "SNAPSHOT role"),
        (document.get("split_policy_ref") == expected_policy, "split-policy identity"),
        (document.get("parent") == expected_parent, "CURATED parent identity"),
        (document.get("partition_source") == expected_source, "partition-source identity"),
        (document.get("adapter_id") == source.manifest.adapter_id, "adapter id"),
        (document.get("symbol") == source.manifest.symbol, "symbol"),
        (document.get("timeframe") == source.manifest.timeframe, "timeframe"),
        (
            document.get("clock_domain") == source.manifest.clock_domain.identifier,
            "clock domain",
        ),
        (document.get("time_unit") == source.manifest.time_unit.value, "time unit"),
        (
            document.get("calendar_time_policy") == policy.calendar_time_policy.value,
            "calendar-time policy",
        ),
        (document.get("columns") == list(columns), "ordered column contract"),
    )
    for accepted, label in checks:
        if not accepted:
            raise _ResumeRefusedError(f"existing SNAPSHOT has wrong {label}")
    if normalized.identity.dataset_id != spec.view_ids.snapshot:
        raise _ResumeRefusedError("normalized SNAPSHOT identity differs from expected id")
    if normalized.source_format is not _ManifestFormat.VIEW_MANIFEST_V1_1:
        raise _ResumeRefusedError("existing SNAPSHOT did not normalize as strict v1.1")
    if normalized.role is not _ViewRole.SNAPSHOT:
        raise _ResumeRefusedError("normalized anchor role is not SNAPSHOT")
    if _canonical_manifest_bytes(document) != raw_bytes:
        raise _ResumeRefusedError("existing SNAPSHOT bytes are not canonical v1.1")

    generator_document = document.get("generator")
    if not isinstance(generator_document, dict):
        raise _ResumeRefusedError("existing SNAPSHOT has no generator provenance")
    expected_generator = spec.generator.as_wire()
    for field in ("name", "version", "platform_git_commit"):
        if generator_document.get(field) != expected_generator[field]:
            raise _ResumeRefusedError(
                f"existing SNAPSHOT generator {field} is incompatible with current generation"
            )
    anchor_generator = _GeneratorProvenance(
        name=str(generator_document["name"]),
        version=str(generator_document["version"]),
        platform_git_commit=str(generator_document["platform_git_commit"]),
    )

    generated_at_utc = document.get("generated_at_utc")
    if not isinstance(generated_at_utc, str) or not generated_at_utc:
        raise _ResumeRefusedError("existing SNAPSHOT has no bundle timestamp")

    binding = document.get("snapshot_binding")
    if not isinstance(binding, dict):
        raise _ResumeRefusedError("existing SNAPSHOT has no snapshot-binding evidence")
    cap = policy.range_for(_ViewRole.LOCKBOX).end
    bound = binding.get("bound_key")
    if isinstance(bound, bool) or not isinstance(bound, int) or bound > cap:
        raise _ResumeRefusedError("existing SNAPSHOT bound exceeds the supplied policy cap")
    if binding.get("policy_cap_key") != cap:
        raise _ResumeRefusedError("existing SNAPSHOT carries the wrong policy cap key")
    if binding.get("policy_cap_encoded") != spec.policy_cap_encoded:
        raise _ResumeRefusedError("existing SNAPSHOT carries the wrong encoded policy cap")
    if binding.get("method") != _BINDING_METHOD:
        raise _ResumeRefusedError("existing SNAPSHOT carries an incompatible binding method")
    expected_event_id = _binding_event_id(
        source=source.identity,
        partition_source=partition_source,
        policy=policy,
        snapshot_view_id=spec.view_ids.snapshot,
        generated_at_utc=generated_at_utc,
        generator=anchor_generator,
        policy_cap_encoded=spec.policy_cap_encoded,
    )
    if binding.get("audit_event_id") != expected_event_id:
        raise _ResumeRefusedError(
            "existing SNAPSHOT carries an incompatible binding event id"
        )
    admitted_range = document.get("admitted_native_range")
    if not isinstance(admitted_range, dict) or admitted_range.get("end") != bound:
        raise _ResumeRefusedError("existing SNAPSHOT bound differs from its admitted range")
    return _ResumeAnchor(
        path=path,
        raw_bytes=raw_bytes,
        manifest_sha256=_hashlib.sha256(raw_bytes).hexdigest(),
        generated_at_utc=generated_at_utc,
        generator=anchor_generator,
        snapshot_binding=_MappingProxyType(dict(binding)),
    )


def _canonical_manifest_bytes(document: _Mapping[str, object]) -> bytes:
    """Serialize exact deterministic v1.1 bytes with one trailing newline."""
    try:
        _ViewManifestV11.model_validate(dict(document))
    except _ValidationError as exc:
        raise _ViewGenerationError(
            f"generated manifest fails strict v1.1 validation: {exc}"
        ) from exc
    try:
        text = _json.dumps(
            dict(document),
            allow_nan=False,
            ensure_ascii=False,
            indent=2,
            sort_keys=True,
        )
    except (TypeError, ValueError, UnicodeError) as exc:
        raise _ViewGenerationError(f"manifest is not canonical JSON data: {exc}") from exc
    return f"{text}\n".encode()


def _manifest_path(views_root: _Path, view_id: str) -> _Path:
    """Return the one registry-discoverable path for an explicit view id."""
    return views_root / view_id / _MANIFEST_FILENAME


def _validate_views_root(path: _Path) -> _Path:
    """Require an existing absolute root with no symlink-based relocation."""
    try:
        resolved = path.resolve(strict=True)
    except OSError as exc:
        raise _ViewGenerationError(f"cannot resolve views root {path}: {exc}") from exc
    if not path.is_dir():
        raise _ViewGenerationError(f"views root must already exist: {path}")
    if resolved != path:
        raise _ViewGenerationError(
            "views_root must be canonical and must not traverse symlinks"
        )
    return resolved


def _reject_source_root_overlap(
    *,
    views_root: _Path,
    source_root: _Path,
    partition_directory: _Path,
) -> None:
    """Keep generated files outside both metadata and physical source trees."""
    for label, source_path in (
        ("source registry root", source_root),
        ("partition-source directory", partition_directory),
    ):
        if (
            views_root == source_path
            or views_root in source_path.parents
            or source_path in views_root.parents
        ):
            raise _ViewGenerationError(
                f"generated views root must be separate from {label} {source_path}"
            )


def _reject_registry_id_collisions(
    *,
    registry: _DatasetRegistry,
    views_root: _Path,
    view_ids: _ViewIds,
) -> None:
    """Reject generated ids already owned by any unrelated registry entry."""
    expected = {
        view_id: (role, _manifest_path(views_root, view_id))
        for role, view_id in view_ids.items()
    }
    for entry in registry.all_manifests_for_diagnostics():
        expected_entry = expected.get(entry.manifest.dataset_id)
        if expected_entry is None:
            continue
        role, path = expected_entry
        if (
            entry.manifest_path.resolve() != path
            or entry.manifest.source_format is not _ManifestFormat.VIEW_MANIFEST_V1_1
            or entry.manifest.role is not role
        ):
            raise _ViewGenerationError(
                f"generated view id {entry.manifest.dataset_id!r} collides with "
                f"registered manifest {entry.manifest_path}"
            )


def _checked_manifest_path(views_root: _Path, view_id: str) -> _Path:
    """Validate an existing generated slot without following a child symlink."""
    path = _manifest_path(views_root, view_id)
    view_directory = path.parent
    if view_directory.exists() or view_directory.is_symlink():
        if view_directory.is_symlink() or not view_directory.is_dir():
            raise _ResumeRefusedError(
                f"generated view directory must be a real directory: {view_directory}"
            )
        if view_directory.resolve() != view_directory:
            raise _ResumeRefusedError(
                f"generated view directory must not traverse symlinks: {view_directory}"
            )
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise _ResumeRefusedError(
            f"generated manifest slot must be a regular file: {path}"
        )
    return path


def _publish_manifest_bytes(path: _Path, payload: bytes) -> bool:
    """Create only the containing view directory, then use the atomic writer."""
    try:
        _ensure_durable_directory(path.parent)
    except OSError as exc:
        raise _ViewGenerationError(
            f"cannot create generated view directory {path.parent}: {exc}"
        ) from exc
    return _publish_immutable_bytes(path, payload)
